# 4. 在 Cursor 里调试的简要步骤
# ------------------------------------------------------------
# 1. 在某一行左侧空白处点击，出现红点 = 断点
# 2. 按 F5（或 Run and Debug），选择 Python File
# 3. 程序会在断点处暂停，可查看变量当前值
# 4. 用顶部按钮：继续 / 单步跳过 / 单步进入
# 5. 调试结束后，记得关掉不需要的断点

