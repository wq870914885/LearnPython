# ------------------------------------------------------------
# 1. 注释：给代码写「说明书」
# ------------------------------------------------------------
# 单行注释：以 # 开头，解释器会忽略这一行后面的内容
# 用途：说明意图、临时关掉某段代码、给自己留笔记

print("这行会执行")  # 行尾也可以写注释
# print("这行不会执行，因为被注释掉了")

# 多行说明可以用多个 #，或者用三引号字符串（见下方「文档字符串」）
"""
三引号包起来的文字叫多行字符串。
单独放着时，常常当作「块注释」或模块说明来用。
它本身是字符串，只是没有赋给变量时，一般不影响程序逻辑。
"""

# ------------------------------------------------------------
# 2. 输出函数 print() 常用写法
# ------------------------------------------------------------

# 2.1 输出多个值（默认用空格隔开）
print("姓名", "小红", "分数", 95)

# 2.2 自定义分隔符 sep
print("2026", "08", "12", sep="-")   # 2026-08-12
print("A", "B", "C", sep="")         # ABC（无分隔）

# 2.3 自定义结尾 end（默认是换行 \n）
print("同一行继续", end="...")
print("接着输出")

# 2.4 格式化输出（推荐 f-string，Python 3.6+）
score = 95
subject = "数学"
print(f"{subject}成绩：{score} 分")
print(f"明年分数如果 +5：{score + 5}")

# 2.5 旧式写法（了解即可）
print("{}成绩：{} 分".format(subject, score))
print("%s成绩：%d 分" % (subject, score))

# ------------------------------------------------------------
# 3. 什么是 debug（调试）？
# ------------------------------------------------------------
# debug = 找出程序「为什么和预期不一样」
# 常见手段：
#   1) 读报错信息（错误类型 + 行号）
#   2) 用 print 打印关键变量，观察中间结果
#   3) 用断点逐步执行（Cursor / VS Code 左侧点行号，再按 F5）

# ---- 3.1 用 print 调试：定位计算错误 ----
a = 10
b = 3
# 假设你以为结果是 13，实际却不对——先打印中间值
print("[debug] a =", a, "b =", b)
result = a + b
print("[debug] result =", result)

# ---- 3.2 常见逻辑 bug：看起来能跑，但结果错 ----
# 例：想统计 1+2+3，却写成了覆盖赋值
total = 0
total = 1
total = 2
total = 3
print("错误写法得到的 total =", total)  # 结果是 3，不是 6

total = 0
total = total + 1
total = total + 2
total = total + 3
print("正确累加得到的 total =", total)  # 6

