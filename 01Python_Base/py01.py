# 1. Python 是什么？
# ------------------------------------------------------------
# - Python 是一种解释型语言：写好 .py 文件后，用解释器一行行执行
# - 特点：语法简洁、适合入门、用途广（脚本、数据分析、Web、自动化等）
# - 文件扩展名通常是 .py

# ------------------------------------------------------------
# 2. 第一个程序：让电脑「说话」
# ------------------------------------------------------------
# print() 是输出函数，会把括号里的内容打印到终端

print("Hello, Python!")
print("我的第一个程序")

# 也可以输出数字、计算结果
print(1 + 1)
print(3 * 4)

# ------------------------------------------------------------
# 3. 变量：给数据起名字
# ------------------------------------------------------------
# 变量名 = 值
# 等号表示「赋值」，不是数学里的相等

name = "小明"
age = 18
print(name)
print(age)

# 变量可以参与运算或拼接输出
print("姓名:", name, "年龄:", age)

