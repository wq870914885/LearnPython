# 4. 常见 bug（错误）——请对照理解，不要直接「照抄错的」
# ------------------------------------------------------------
# Python 报错时，终端会给出：
#   - 错误类型（如 SyntaxError、NameError）
#   - 出错大概在哪一行
# 初学者要学会「读报错」，而不是慌张

# ---- 4.1 SyntaxError：语法错误 ----
# 下面这行如果取消注释，程序无法运行（少了右括号）
# print("少写括号"

# ---- 4.2 NameError：名字未定义 ----
# 使用了不存在的变量名
# print(undefined_var)

# ---- 4.3 IndentationError：缩进错误 ----
# Python 用缩进表示代码块，空格数量必须一致
# 下面如果取消注释会报错（随便多缩进了一行）
#   print("缩进不对")

# ---- 4.4 TypeError：类型用错 ----
# 字符串和数字不能直接用 + 拼接
# print("年龄是" + 18)   # 错误
print("年龄是" + str(18))  # 正确：先把数字转成字符串
print("年龄是", 18)        # 也可以：用逗号分隔，print 会自动空格拼接

# ---- 4.5 引号不匹配 ----
# print("两边引号要一样')  # 错误
print("两边引号要一样")     # 正确
print('单引号也可以')

